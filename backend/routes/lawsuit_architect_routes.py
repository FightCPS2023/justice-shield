"""Lawsuit Architect Routes - 42 U.S.C. §1983 complaint generator"""
from typing import List, Optional
from datetime import datetime, timezone
import uuid
import base64
import io

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel, Field
from reportlab.pdfgen import canvas

from auth import get_current_user
from database import get_db

router = APIRouter()


class PlaintiffInfo(BaseModel):
    name: str
    address: str
    city: str
    state: str
    zip: str
    phone: Optional[str] = None
    email: Optional[str] = None


class DefendantInfo(BaseModel):
    name: str
    badge: Optional[str] = None
    title: Optional[str] = None
    employer: Optional[str] = None


class AgencyInfo(BaseModel):
    name: str
    address: Optional[str] = None
    city: Optional[str] = None
    state: Optional[str] = None
    zip: Optional[str] = None


class IncidentInfo(BaseModel):
    date: str
    location: str
    district: Optional[str] = None


class ViolationEntry(BaseModel):
    matched_phrase: str
    amendments: List[str] = Field(default_factory=list)
    legal_citations: List[str] = Field(default_factory=list)
    description: str


class BondDetails(BaseModel):
    bond_number: Optional[str] = None
    surety_company: Optional[str] = None
    coverage_amount: Optional[str] = None
    effective_dates: Optional[str] = None
    oath_on_file: Optional[bool] = None


class ChildrenInfo(BaseModel):
    count: Optional[int] = None
    ages: List[str] = Field(default_factory=list)


class ComplaintGenerateRequest(BaseModel):
    plaintiff: PlaintiffInfo
    defendant: DefendantInfo
    agency: AgencyInfo
    incident: IncidentInfo
    violations: List[ViolationEntry] = Field(default_factory=list)
    bond_details: BondDetails = BondDetails()
    children: ChildrenInfo = ChildrenInfo()
    transcripts: List[str] = Field(default_factory=list)
    output_format: str = "pdf"


def _format_facts(violations: List[ViolationEntry], transcripts: List[str]) -> List[str]:
    facts = []
    for v in violations:
        desc = v.description.strip()
        if v.matched_phrase:
            desc = f"{desc} (Matched phrase: {v.matched_phrase})"
        facts.append(desc)
    for t in transcripts:
        facts.append(f"Transcript excerpt: {t.strip()}")
    return facts or ["Plaintiff reserves the right to supplement factual allegations as discovery proceeds."]


def build_complaint_markdown(payload: ComplaintGenerateRequest) -> str:
    complaint_id = str(uuid.uuid4())
    district = payload.incident.district or "[DISTRICT]"
    facts = _format_facts(payload.violations, payload.transcripts)
    violations_text = "\n".join([f"{idx + 1}. {fact}" for idx, fact in enumerate(facts)])

    violations_list = "\n".join([
        f"- {v.matched_phrase}: {', '.join(v.amendments) or 'Constitutional violation'} :: {v.description}"
        for v in payload.violations
    ]) or "- No violations entered."

    bond_block = ""
    if payload.bond_details and any([
        payload.bond_details.bond_number,
        payload.bond_details.surety_company,
        payload.bond_details.coverage_amount,
        payload.bond_details.effective_dates,
        payload.bond_details.oath_on_file is not None
    ]):
        bond_block = (
            f"\nBond Details:\n"
            f"- Bond Number: {payload.bond_details.bond_number or 'N/A'}\n"
            f"- Surety Company: {payload.bond_details.surety_company or 'N/A'}\n"
            f"- Coverage Amount: {payload.bond_details.coverage_amount or 'N/A'}\n"
            f"- Effective Dates: {payload.bond_details.effective_dates or 'N/A'}\n"
            f"- Oath on File: {'Yes' if payload.bond_details.oath_on_file else 'No/Unknown'}\n"
        )

    children_block = ""
    if payload.children and (payload.children.count or payload.children.ages):
        children_block = (
            f"\nChildren Impacted: {payload.children.count or len(payload.children.ages) or 'N/A'}\n"
            f"Ages: {', '.join(payload.children.ages) or 'N/A'}\n"
        )

    markdown = f"""# UNITED STATES DISTRICT COURT\n{district}\n\n## COMPLAINT FOR VIOLATION OF CIVIL RIGHTS (42 U.S.C. §1983)\nGenerated by Justice Shield — {datetime.now(timezone.utc).strftime('%Y-%m-%d')}\n\n### CAPTION\n**{payload.plaintiff.name}**, Plaintiff\n\nvs.\n\n**{payload.defendant.name}**, Defendant\n\nCivil Action No.: [TO BE ASSIGNED]\n\n### INTRODUCTION\nPlaintiff brings this civil rights action pursuant to 42 U.S.C. §1983 and §1988 to redress violations of the United States Constitution and to obtain declaratory, injunctive, compensatory, and punitive relief.\n\n### JURISDICTION & VENUE\n1. This Court has jurisdiction under 28 U.S.C. §§1331 and 1343.\n2. Venue is proper under 28 U.S.C. §1391 because the events occurred in this district.\n\n### PARTIES\n**Plaintiff:** {payload.plaintiff.name}, {payload.plaintiff.address}, {payload.plaintiff.city}, {payload.plaintiff.state} {payload.plaintiff.zip}.\n**Defendant:** {payload.defendant.name}, {payload.defendant.title or 'Caseworker'}, {payload.defendant.employer or 'Agency'}. Badge/ID: {payload.defendant.badge or 'Unknown'}.\n**Agency:** {payload.agency.name}, {payload.agency.address or '[AGENCY ADDRESS]'}, {payload.agency.city or ''} {payload.agency.state or ''} {payload.agency.zip or ''}.\n{children_block}{bond_block}\n### STATEMENT OF FACTS\n{violations_text}\n\n### VIOLATIONS IDENTIFIED\n{violations_list}\n\n### CAUSES OF ACTION\n**COUNT I – Fourth Amendment (Unlawful Search/Seizure)**\nDefendant conducted unconstitutional searches, seizures, or removals without lawful warrant, exigent circumstances, or consent.\n\n**COUNT II – Fourteenth Amendment (Due Process)**\nDefendant deprived Plaintiff of notice, hearing, and fair process in violation of the Fourteenth Amendment.\n\n**COUNT III – Fourteenth Amendment (Parental Rights)**\nDefendant interfered with fundamental parental rights without compelling state interest or due process protections.\n\n### PRAYER FOR RELIEF\nPlaintiff respectfully requests:\n1. Declaratory judgment that Defendant’s actions violated the Constitution.\n2. Injunctive relief prohibiting further unconstitutional conduct.\n3. Compensatory damages in an amount to be proven.\n4. Punitive damages to deter future misconduct.\n5. Attorney’s fees and costs pursuant to 42 U.S.C. §1988.\n6. Any further relief the Court deems just and proper.\n\n### JURY TRIAL DEMAND\nPlaintiff demands a trial by jury on all issues so triable.\n\n### SIGNATURE BLOCK\n____________________________________\n{payload.plaintiff.name}\n{payload.plaintiff.address}\n{payload.plaintiff.city}, {payload.plaintiff.state} {payload.plaintiff.zip}\nPhone: {payload.plaintiff.phone or '[PHONE]'}\nEmail: {payload.plaintiff.email or '[EMAIL]'}\n\n### DISCLAIMER\nThis template is generated for informational purposes only and does not constitute legal advice. Consult a licensed attorney before filing.\n\nComplaint ID: {complaint_id}\n"""
    return markdown


def _render_pdf_from_text(text: str) -> bytes:
    buffer = io.BytesIO()
    pdf = canvas.Canvas(buffer)
    pdf.setFont("Times-Roman", 11)
    y = 760
    for raw_line in text.splitlines():
        line = raw_line.replace("#", "").strip()
        if not line:
            y -= 14
            continue
        if y < 72:
            pdf.showPage()
            pdf.setFont("Times-Roman", 11)
            y = 760
        pdf.drawString(72, y, line[:140])
        y -= 14
    pdf.save()
    buffer.seek(0)
    return buffer.read()


@router.post("/api/lawsuit-architect/generate")
async def generate_complaint(request: ComplaintGenerateRequest, current_user: dict = Depends(get_current_user)):
    db = get_db()
    complaint_id = str(uuid.uuid4())
    markdown = build_complaint_markdown(request)

    pdf_base64 = None
    if request.output_format in ("pdf", "markdown+pdf", "both"):
        pdf_bytes = _render_pdf_from_text(markdown)
        pdf_base64 = base64.b64encode(pdf_bytes).decode("utf-8")

    doc = {
        "user_id": current_user["user_id"],
        "complaint_id": complaint_id,
        "created_at": datetime.now(timezone.utc).isoformat(),
        "status": "generated",
        "plaintiff": request.plaintiff.model_dump(),
        "defendant": request.defendant.model_dump(),
        "agency": request.agency.model_dump(),
        "incident": request.incident.model_dump(),
        "violations": [v.model_dump() for v in request.violations],
        "bond_details": request.bond_details.model_dump(),
        "children": request.children.model_dump(),
        "output_format": request.output_format,
        "generated_document": markdown,
        "pdf_base64": pdf_base64,
        "transcripts": request.transcripts
    }

    await db.complaints_1983.insert_one(doc)

    return {
        "complaint_id": complaint_id,
        "output_format": request.output_format,
        "generated_document": markdown,
        "pdf_base64": pdf_base64
    }


@router.get("/api/lawsuit-architect/complaints")
async def list_complaints(current_user: dict = Depends(get_current_user)):
    db = get_db()
    results = []
    async for doc in db.complaints_1983.find({"user_id": current_user["user_id"]}, {"_id": 0, "pdf_base64": 0}).sort("created_at", -1):
        results.append(doc)
    return {"complaints": results}


@router.get("/api/lawsuit-architect/complaints/{complaint_id}")
async def get_complaint(complaint_id: str, current_user: dict = Depends(get_current_user)):
    db = get_db()
    doc = await db.complaints_1983.find_one({"complaint_id": complaint_id, "user_id": current_user["user_id"]}, {"_id": 0})
    if not doc:
        raise HTTPException(status_code=404, detail="Complaint not found")
    return doc


@router.delete("/api/lawsuit-architect/complaints/{complaint_id}")
async def delete_complaint(complaint_id: str, current_user: dict = Depends(get_current_user)):
    db = get_db()
    result = await db.complaints_1983.delete_one({"complaint_id": complaint_id, "user_id": current_user["user_id"]})
    if result.deleted_count == 0:
        raise HTTPException(status_code=404, detail="Complaint not found")
    return {"success": True}
